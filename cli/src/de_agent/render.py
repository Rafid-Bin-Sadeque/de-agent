def postgres_signals(data: dict[str, Any]) -> list[str]:
    sig: list[str] = []
    server = data.get("server") or {}
    xid = server.get("xid_wraparound_pct")
    if isinstance(xid, (int, float)) and xid >= XID_PCT_MIN:
        sig.append(f"xid age {xid:.0f}% of wraparound")
    total, mx = server.get("connections_total"), server.get("max_connections")
    if isinstance(total, (int, float)) and isinstance(mx, (int, float)) and mx and total / mx * 100 >= CONN_PCT_MIN:
        sig.append(f"connections {int(total)} of {int(mx)} ({total / mx * 100:.0f}%)")
    hit = server.get("cache_hit_pct")
    if isinstance(hit, (int, float)) and hit < CACHE_HIT_MIN:
        sig.append(f"cache hit ratio {hit:.1f}% (< {CACHE_HIT_MIN:.0f}%)")
    for t in sorted(data.get("tables") or [], key=lambda r: (str(r.get("schema")), str(r.get("name")))):
        dead, pct = t.get("n_dead_tup"), t.get("dead_pct")
        if isinstance(dead, (int, float)) and isinstance(pct, (int, float)) \
                and pct >= DEAD_PCT_MIN and dead >= DEAD_TUP_MIN:
            sig.append(f"table {t['schema']}.{t['name']} {pct:.0f}% dead tuples")
    est = (data.get("meta") or {}).get("sizes_estimated")
    if est:
        sig.append(f"sizes of {', '.join(est)} are estimates: a relation is locked (lock timeout)")
    n_long = len(data.get("long_queries") or [])
    if n_long:
        thr = (data.get("meta") or {}).get("long_query_seconds", DEFAULT_LONG_QUERY_S)
        noun = "query" if n_long == 1 else "queries"
        sig.append(f"{n_long} {noun} running > {human_duration(thr)}")
    n_block = len(data.get("blocking") or [])
    if n_block:
        sig.append(f"{n_block} blocked session(s)")
    for s in sorted(data.get("replication_slots") or [], key=lambda r: str(r.get("slot_name"))):
        lag = s.get("lag_bytes")
        inactive = s.get("active") is False
        big = isinstance(lag, (int, float)) and lag > SLOT_LAG_BYTES
        if inactive or big:
            state = "inactive" if inactive else "active"
            sig.append(f"slot {s['slot_name']} {state}, lag {human_bytes(lag)}")
    n_idx = len(data.get("unused_indexes") or [])
    if n_idx:
        total_b = sum(i.get("size_bytes") or 0 for i in data["unused_indexes"])
        sig.append(f"{n_idx} unused index(es), {human_bytes(total_b)}")
    return sig


def _postgres_body(data: dict[str, Any]) -> list[str]:
    out: list[str] = []
    s = data.get("server")
    if s:
        conns = s.get("connections") or {}
        by_state = ", ".join(f"{k} {v}" for k, v in sorted(conns.items())) or "-"
        out += ["## Server", ""]
        out += _table(["key", "value"], [
            ["version", str(s.get("version", "-")).split(" on ")[0]],
            ["uptime", human_duration(s.get("uptime_s"))],
            ["connections", f"{_num(s.get('connections_total'))} of {_num(s.get('max_connections'))} ({by_state})"],
            ["cache hit", "-" if s.get("cache_hit_pct") is None else f"{s['cache_hit_pct']:.1f}%"],
            ["oldest xid age", f"{_num(s.get('oldest_xid_age'))} ({_num(s.get('xid_wraparound_pct'))}% of wraparound)"],
        ])
        out.append("")
    dbs = data.get("databases")
    if dbs is not None:
        rows = sorted(dbs, key=lambda r: (-(r.get("size_bytes") or 0), str(r.get("name"))))
        out += ["## Databases", ""] + _table(["name", "size"], [[r["name"], human_bytes(r.get("size_bytes"))] for r in rows]) + [""]
    sch = data.get("schemas")
    if sch is not None:
        rows = sorted(sch, key=lambda r: (-(r.get("total_bytes") or 0), str(r.get("name"))))
        out += ["## Schemas", ""] + _table(["name", "tables", "size"], [
            [r["name"], _num(r.get("table_count")), human_bytes(r.get("total_bytes"))] for r in rows]) + [""]
    tabs = data.get("tables")
    if tabs is not None:
        rows = sorted(tabs, key=lambda r: (-(r.get("total_bytes") or 0), str(r.get("schema")), str(r.get("name"))))
        out += ["## Tables (top by size)", ""] + _table(
            ["table", "total", "heap", "index", "live", "dead", "dead %", "last autovacuum", "last autoanalyze",
             "seq scan", "idx scan"],
            [[f"{r['schema']}.{r['name']}", human_bytes(r.get("total_bytes")), human_bytes(r.get("table_bytes")),
              human_bytes(r.get("index_bytes")), _num(r.get("n_live_tup")), _num(r.get("n_dead_tup")),
              "-" if r.get("dead_pct") is None else f"{r['dead_pct']:.1f}", _ts(r.get("last_autovacuum")),
              _ts(r.get("last_autoanalyze")), _num(r.get("seq_scan")), _num(r.get("idx_scan"))] for r in rows]) + [""]
    idx = data.get("unused_indexes")
    if idx:
        rows = sorted(idx, key=lambda r: (-(r.get("size_bytes") or 0), str(r.get("schema")), str(r.get("table")), str(r.get("index"))))
        out += ["## Unused indexes", ""] + _table(["index", "table", "size"], [
            [f"{r['schema']}.{r['index']}", f"{r['schema']}.{r['table']}", human_bytes(r.get("size_bytes"))] for r in rows]) + [""]
    lq = data.get("long_queries")
    if lq:
        rows = sorted(lq, key=lambda r: (-(r.get("duration_s") or 0), r.get("pid") or 0))
        out += ["## Long-running queries", ""] + _table(["pid", "user", "duration", "state", "wait", "query"], [
            [str(r.get("pid")), str(r.get("user", "-")), human_duration(r.get("duration_s")), str(r.get("state", "-")),
             str(r.get("wait_event") or "-"), str(r.get("query", ""))[:120]] for r in rows]) + [""]
    bl = data.get("blocking")
    if bl:
        rows = sorted(bl, key=lambda r: (-(r.get("wait_s") or 0), r.get("blocked_pid") or 0, r.get("blocker_pid") or 0))
        out += ["## Blocking", ""] + _table(["blocked pid", "blocker pid", "waiting", "blocked query", "blocker query"], [
            [str(r.get("blocked_pid")), str(r.get("blocker_pid")), human_duration(r.get("wait_s")),
             str(r.get("blocked_query", ""))[:80], str(r.get("blocker_query", ""))[:80]] for r in rows]) + [""]
    sl = data.get("replication_slots")
    if sl:
        rows = sorted(sl, key=lambda r: str(r.get("slot_name")))
        out += ["## Replication slots", ""] + _table(["slot", "plugin", "active", "lag"], [
            [r["slot_name"], str(r.get("plugin") or "-"), _num(r.get("active")), human_bytes(r.get("lag_bytes"))]
            for r in rows]) + [""]
    st = data.get("settings")
    if st:
        rows = sorted(st, key=lambda r: str(r.get("name")))
        out += ["## Settings", ""] + _table(["name", "value"], [
            [r["name"], f"{r.get('setting')} {r.get('unit') or ''}".strip()] for r in rows]) + [""]
    ts = data.get("top_statements")
    if ts:
        out += ["## Top statements (pg_stat_statements)", ""] + _table(["query", "calls", "total ms", "mean ms"], [
            [str(r.get("query", ""))[:100], _num(r.get("calls")), _num(r.get("total_exec_ms")), _num(r.get("mean_exec_ms"))]
            for r in ts]) + [""]
    return out


# ---- airflow ----------------------------------------------------------------------------------

DURATION_REGRESSION_X = 2.0
DURATION_REGRESSION_MIN_S = 300
RECENT_FAIL_WINDOW_S = 24 * 3600


def _dt(v: Any) -> datetime | None:
    try:
        return datetime.fromisoformat(str(v).replace("Z", "+00:00")).astimezone(timezone.utc)
    except ValueError:
        return None


def _median(xs: list[float]) -> float:
    xs = sorted(xs)
    n = len(xs)
    return xs[n // 2] if n % 2 else (xs[n // 2 - 1] + xs[n // 2]) / 2


def _recovery(runs: list[dict[str, Any]], failed_runs: list[dict[str, Any]],
              failed_tasks: list[dict[str, Any]]) -> tuple[str, str] | None:
    """(state, time) of the latest run when it succeeded AFTER the last failure seen in the 24 h window, else None."""
    done = [(_dt(r.get("start")), r) for r in runs if _dt(r.get("start")) is not None]
    if not done:
        return None
    last = max(done, key=lambda t: t[0])[1]
    if last.get("state") != "success":
        return None
    last_t = _dt(last.get("end") or last.get("start"))
    fail_ts = [t for t in (_dt(r.get("end") or r.get("start")) for r in failed_runs) if t]
    fail_ts += [t for t in (_dt(f.get("start")) for f in failed_tasks) if t]
    if last_t is None or not fail_ts or last_t <= max(fail_ts):
        return None
    return "success", str(last.get("end") or last.get("start"))


def airflow_signals(data: dict[str, Any]) -> list[str]:
    from de_agent.collectors._airflow_core import schedule_interval_s

    sig: list[str] = []
    now = _dt((data.get("meta") or {}).get("collected_at")) or datetime.now(timezone.utc)
    dags = {d["dag_id"]: d for d in data.get("dags") or []}
    runs_by: dict[str, list[dict[str, Any]]] = {}
    for r in data.get("runs") or []:
        runs_by.setdefault(r["dag_id"], []).append(r)
    fails_by: dict[str, list[dict[str, Any]]] = {}
    for f in data.get("failures_24h") or []:
        fails_by.setdefault(str(f.get("dag_id")), []).append(f)
    recovered: list[str] = []  # failure signals whose DAG has since run clean: ranked below the active ones
    for dag_id in sorted(set(fails_by) | set(runs_by)):
        failed_runs = [r for r in runs_by.get(dag_id, []) if r.get("state") == "failed"
                       and (_dt(r.get("end") or r.get("start")) or now) >= now - timedelta(seconds=RECENT_FAIL_WINDOW_S)]
        tasks = sorted({str(f.get("task_id")) for f in fails_by.get(dag_id, [])})
        if failed_runs or tasks:
            n = len(failed_runs)
            text = f"dag {dag_id}: {n} failed run(s) in 24h" + (f" (tasks: {', '.join(tasks)})" if tasks else "")
            rec = _recovery(runs_by.get(dag_id, []), failed_runs, fails_by.get(dag_id, []))
            if rec:
                recovered.append(f"{text} (recovered: last run {rec[0]} at {_ts(rec[1])})")
            else:
                sig.append(text)
    ie = data.get("import_errors") or []
    if ie:
        sig.append(f"{len(ie)} DAG import error(s): " + ", ".join(sorted(str(e.get("filename")) for e in ie)))
    for dag_id in sorted(dags):
        d = dags[dag_id]
        if d.get("is_paused"):
            continue
        runs = runs_by.get(dag_id, [])
        interval = schedule_interval_s(d.get("schedule"), runs)
        if interval:
            nxt = _dt(d.get("next_dagrun"))
            ok = [_dt(r.get("end") or r.get("start")) for r in runs if r.get("state") == "success"]
            ok = [t for t in ok if t]
            late = False
            if nxt and (now - nxt).total_seconds() > interval:
                late = True
            elif runs and (not ok or (now - max(ok)).total_seconds() > 2 * interval):
                late = True
            if late:
                sig.append(f"dag {dag_id} is late (schedule {d.get('schedule')})")
        done = sorted((r for r in runs if r.get("state") == "success" and r.get("duration_s") is not None),
                      key=lambda r: str(r.get("start")), reverse=True)
        if len(done) >= 5:
            last, prev = done[0]["duration_s"], [r["duration_s"] for r in done[1:5]]
            if last > DURATION_REGRESSION_X * _median(prev) and last > DURATION_REGRESSION_MIN_S:
                sig.append(f"dag {dag_id}: last run {human_duration(last)}, > 2x the median of the previous 4")
    for ds in sorted(data.get("datasets") or [], key=lambda r: str(r.get("uri"))):
        if not ds.get("consuming_dags"):
            continue
        last = _dt(ds.get("last_event"))
        if last is None or (now - last).total_seconds() > 24 * 3600:
            sig.append(f"dataset {ds['uri']} has consumers but no event in 24h")
    for p in sorted(data.get("pools") or [], key=lambda r: str(r.get("name"))):
        if isinstance(p.get("queued"), (int, float)) and p["queued"] > 0:
            sig.append(f"pool {p['name']}: {int(p['queued'])} task(s) queued")
    return sig + recovered


def _airflow_body(data: dict[str, Any]) -> list[str]:
    out: list[str] = []
    v = data.get("version")
    if v:
        out += ["## Version", "", f"Airflow {v.get('version')} (REST {v.get('api')})", ""]
    dags = data.get("dags")
    if dags is not None:
        rows = sorted(dags, key=lambda r: str(r.get("dag_id")))
        out += ["## DAGs", ""] + _table(["dag", "paused", "schedule", "tags", "next run", "import errors"], [
            [r["dag_id"], _num(r.get("is_paused")), str(r.get("schedule_desc") or r.get("schedule") or "-"),
             ", ".join(r.get("tags") or []) or "-", _ts(r.get("next_dagrun")), _num(r.get("has_import_errors"))]
            for r in rows]) + [""]
    runs = data.get("runs")
    if runs:
        rows = sorted(runs, key=lambda r: (str(r.get("dag_id")), str(r.get("start")) == "None", str(r.get("start"))),
                      reverse=False)
        out += ["## Recent runs", ""] + _table(["dag", "run", "state", "start", "duration"], [
            [r["dag_id"], r["run_id"], str(r.get("state")), _ts(r.get("start")), human_duration(r.get("duration_s"))]
            for r in rows]) + [""]
    fl = data.get("failures_24h")
    if fl:
        out += ["## Failures (24h)", ""] + _table(["dag", "task", "try", "state", "start"], [
            [r["dag_id"], r["task_id"], str(r.get("try")), str(r.get("state")), _ts(r.get("start"))]
            for r in sorted(fl, key=lambda r: (str(r.get("dag_id")), str(r.get("task_id")), r.get("try") or 0))]) + [""]
        for r in sorted(fl, key=lambda r: (str(r.get("dag_id")), str(r.get("task_id")), r.get("try") or 0)):
            if r.get("log_tail"):
                out += [f"### log tail: {r['dag_id']} / {r['task_id']} (try {r.get('try')})", "", "```"]
                out += str(r["log_tail"]).splitlines()[-15:] + ["```", ""]
    ie = data.get("import_errors")
    if ie:
        out += ["## Import errors", ""]
        for e in sorted(ie, key=lambda r: str(r.get("filename"))):
            out += [f"### {e.get('filename')}", "", "```"] + str(e.get("stack", "")).splitlines() + ["```", ""]
    ds = data.get("datasets")
    if ds:
        out += ["## Datasets", ""] + _table(["uri", "produced by", "consumed by", "last event"], [
            [r["uri"], ", ".join(r.get("producing_tasks") or []) or "-", ", ".join(r.get("consuming_dags") or []) or "-",
             _ts(r.get("last_event"))] for r in sorted(ds, key=lambda r: str(r.get("uri")))]) + [""]
    pl = data.get("pools")
    if pl:
        out += ["## Pools", ""] + _table(["pool", "slots", "occupied", "queued"], [
            [r["name"], _num(r.get("slots")), _num(r.get("occupied")), _num(r.get("queued"))]
            for r in sorted(pl, key=lambda r: str(r.get("name")))]) + [""]
    return out


# ---- dbt --------------------------------------------------------------------------------------

DBT_RUN_STALE_S = 24 * 3600


def dbt_signals(data: dict[str, Any]) -> list[str]:
    sig: list[str] = []
    lr = data.get("last_run") or {}
    bad = sum(int(lr.get(k) or 0) for k in ("n_error", "n_fail", "n_failed"))
    if bad:
        names = ", ".join(n["unique_id"] for n in (data.get("failing_nodes") or [])[:3])
        sig.append(f"dbt last run: {bad} error/fail result(s)" + (f" ({names})" if names else ""))
    tests = [t for t in data.get("tests") or [] if t.get("status") in ("fail", "error", "failed")]
    if tests:
        models = sorted({str(t.get("model")) for t in tests if t.get("model")})
        sig.append(f"{len(tests)} dbt test(s) failing" + (f", guarding {', '.join(models)}" if models else ""))
    warn = [t for t in data.get("tests") or [] if t.get("status") == "warn"]
    if warn:
        sig.append(f"{len(warn)} dbt test(s) warning")
    for f in sorted(data.get("freshness") or [], key=lambda r: str(r.get("unique_id"))):
        if f.get("status") in ("warn", "error"):
            sig.append(f"source freshness {f['status']}: {f['unique_id']} ({human_duration(f.get('age_s'))} old)")
    ran = _dt((data.get("meta") or {}).get("last_run_at"))
    if ran is not None:
        collected = _dt((data.get("meta") or {}).get("collected_at")) or datetime.now(timezone.utc)
        if (collected - ran).total_seconds() > DBT_RUN_STALE_S:
            sig.append(f"dbt last run is {human_duration((collected - ran).total_seconds())} old")
    return sig


def _dbt_body(data: dict[str, Any]) -> list[str]:
    out: list[str] = []
    p = data.get("project")
    if p:
        out += ["## Project", ""] + _table(["key", "value"], [
            ["name", str(p.get("name"))], ["dbt version", str(p.get("dbt_version"))], ["adapter", str(p.get("adapter"))],
            ["manifest generated", _ts(p.get("generated_at"))], ["manifest schema", f"v{p.get('manifest_schema')}"]]) + [""]
    models = data.get("models")
    if models:
        out += ["## Models", ""] + _table(["folder", "materialization", "count"], [
            [r["folder"], r["materialization"], _num(r["count"])] for r in models]) + [""]
    lr = data.get("last_run")
    if lr:
        counts = ", ".join(f"{k[2:]} {v}" for k, v in sorted(lr.items()) if k.startswith("n_") and k != "nodes")
        out += ["## Last run", ""] + _table(["key", "value"], [
            ["command", str(lr.get("command"))], ["finished", _ts(lr.get("invocation_time"))],
            ["elapsed", human_duration(lr.get("elapsed_s"))], ["nodes", _num(lr.get("nodes"))],
            ["results", counts or "-"]]) + [""]
    fn = data.get("failing_nodes")
    if fn:
        out += ["## Failing nodes", ""] + _table(["node", "status", "message"], [
            [r["unique_id"], r["status"], str(r.get("message", ""))[:200]] for r in fn]) + [""]
    tests = data.get("tests")
    if tests:
        out += ["## Failing / warning tests", ""] + _table(["test", "status", "failures", "guards"], [
            [r["unique_id"], r["status"], _num(r.get("failures")), str(r.get("model") or "-")] for r in tests]) + [""]
    slow = data.get("slowest")
    if slow:
        out += ["## Slowest nodes", ""] + _table(["node", "seconds"], [
            [r["unique_id"], _num(r.get("execution_s"))] for r in slow]) + [""]
    fr = data.get("freshness")
    if fr:
        out += ["## Source freshness", ""] + _table(["source", "status", "max loaded at", "age"], [
            [r["unique_id"], str(r.get("status")), _ts(r.get("max_loaded_at")), human_duration(r.get("age_s"))]
            for r in fr]) + [""]
    ex = data.get("exposures")
    if ex:
        out += ["## Exposures", ""] + _table(["name", "depends on"], [
            [r["name"], ", ".join(r.get("depends_on") or [])] for r in ex]) + [""]
    return out


