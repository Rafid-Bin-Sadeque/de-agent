# Signal thresholds (module constants, M1a section 6)
DEAD_PCT_MIN = 20.0
DEAD_TUP_MIN = 100_000
SLOT_LAG_BYTES = 1024**3
XID_PCT_MIN = 50.0
CONN_PCT_MIN = 80.0
CACHE_HIT_MIN = 95.0
DEFAULT_LONG_QUERY_S = 300

HEADER = "GENERATED by dea snapshot — do not edit"


def human_bytes(n: Any) -> str:
    if not isinstance(n, (int, float)) or isinstance(n, bool):
        return "-"
    n = float(n)
    sign = "-" if n < 0 else ""
    n = abs(n)
    if n < 1024:
        return f"{sign}{int(n)} B"
    for unit in ("KB", "MB", "GB", "TB"):
        n /= 1024.0
        if n < 1024 or unit == "TB":
            return f"{sign}{n:.1f} {unit}"
    return "-"  # pragma: no cover


def human_duration(seconds: Any) -> str:
    if not isinstance(seconds, (int, float)):
        return "-"
    s = int(seconds)
    if s < 60:
        return f"{s} s"
    if s < 3600:
        return f"{s // 60} min"
    if s < 86400:
        return f"{s / 3600:.1f} h"
    return f"{s / 86400:.1f} d"


def _num(v: Any) -> str:
    if v is None:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, int):
        return f"{v:,}"
    if isinstance(v, float):
        return f"{v:,.1f}"
    return str(v)


def _ts(v: Any) -> str:
    if not v:
        return "-"
    return str(v).replace("T", " ")[:16]


def _cell(v: Any) -> str:
    return str(v).replace("|", "\\|").replace("\n", " ").strip() if v is not None else "-"


def _table(headers: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows]
    return out


def _f(d: dict[str, Any], key: str, default: Any = None) -> Any:
    v = d.get(key)
    return default if v is None else v


