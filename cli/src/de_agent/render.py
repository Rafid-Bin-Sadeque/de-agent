SIGNALS: dict[str, Callable[[dict[str, Any]], list[str]]] = {
    "postgres": postgres_signals, "airflow": airflow_signals, "dbt": dbt_signals, "redshift": redshift_signals,
    "aws": aws_signals}
BODIES: dict[str, Callable[[dict[str, Any]], list[str]]] = {
    "postgres": _postgres_body, "airflow": _airflow_body, "dbt": _dbt_body, "redshift": _redshift_body,
    "aws": _aws_body}


def signals_for(result: dict[str, Any]) -> list[str]:
    fn = SIGNALS.get(result.get("type", ""))
    return fn(result.get("data") or {}) if fn else []


def render(result: dict[str, Any]) -> str:
    data = result.get("data") or {}
    body_fn: Callable[[dict[str, Any]], list[str]] | None = BODIES.get(result.get("type", ""))
    lines = [
        "---",
        f"source: {result['source']}",
        f"type: {result['type']}",
        f"generated: {result['collected_at']}",
        f"schema_version: {result['schema_version']}",
        "---",
        "",
        f"# {result['source']} ({result['type']})",
        "",
        f"_{HEADER}._",
        "",
        "## Signals",
        "",
    ]
    sigs = signals_for(result)
    lines += [f"- {s}" for s in sigs] if sigs else ["- none"]
    lines.append("")
    if body_fn:
        lines += body_fn(data)
    errors = result.get("errors") or []
    if errors:
        lines += ["## Errors", ""] + [f"- {e}" for e in errors] + [""]
    return "\n".join(lines).rstrip("\n") + "\n"
