DMS_LATENCY_S = 300.0
DMS_MEM_PCT = 10.0
DMS_CPU_P95 = 85.0
DMS_SWAP_HOURS = 3
GLUE_DURATION_X = 2.0
GLUE_PARTITION_DAYS = 7
FIREHOSE_FRESH_X = 2.0
SPLIT_OVER = 300  # lines: a longer AWS page splits into platform/<source>/<service>.md plus an index
AWS_SERVICES = ("dms", "glue", "s3", "athena", "firehose", "cloudwatch")
AWS_TITLES = {"dms": "DMS", "glue": "Glue", "s3": "S3", "athena": "Athena", "firehose": "Firehose",
              "cloudwatch": "CloudWatch"}


def _within(ts: Any, now: datetime, hours: float) -> bool:
    t = _dt(ts)
    return t is not None and (now - t).total_seconds() <= hours * 3600


def aws_signals(data: dict[str, Any]) -> list[str]:
    meta = data.get("meta") or {}
    now = _dt(meta.get("collected_at")) or datetime.now(timezone.utc)
    sig: list[str] = []
    for t in sorted(data.get("dms_tasks") or [], key=lambda r: str(r.get("id"))):
        tid = t["id"]
        if t.get("status") != "running":
            why = f" ({t['stop_reason']})" if t.get("stop_reason") else ""
            sig.append(f"dms task {tid} is {t.get('status')}{why}")
        if t.get("last_failure_message") and _within(t.get("last_failure_at"), now, 24):
            sig.append(f"dms task {tid} failed in the last 24h: {str(t['last_failure_message'])[:100]}")
        lat = max((x for x in (t.get("cdc_latency_source_p95_s"), t.get("cdc_latency_target_p95_s"))
                   if isinstance(x, (int, float))), default=None)
        if lat is not None and lat > DMS_LATENCY_S:
            sig.append(f"dms task {tid}: CDC latency p95 {lat:.0f} s (> {DMS_LATENCY_S:.0f} s)")
        err, susp = int(t.get("tables_errored") or 0), int(t.get("tables_suspended") or 0)
        if err or susp:
            sig.append(f"dms task {tid}: {err} table(s) errored, {susp} suspended")
    for i in sorted(data.get("dms_instances") or [], key=lambda r: str(r.get("id"))):
        mem = i.get("free_mem_min_pct")
        if isinstance(mem, (int, float)) and mem < DMS_MEM_PCT:
            sig.append(f"dms instance {i['id']}: freeable memory fell to {mem:.0f}% (< {DMS_MEM_PCT:.0f}%)")
        if int(i.get("swap_hours") or 0) >= DMS_SWAP_HOURS:
            sig.append(f"dms instance {i['id']}: swap in use for {i['swap_hours']} of the last 24 h")
        cpu = i.get("cpu_p95")
        if isinstance(cpu, (int, float)) and cpu > DMS_CPU_P95:
            sig.append(f"dms instance {i['id']}: CPU p95 {cpu:.0f}% (> {DMS_CPU_P95:.0f}%)")
    runs_by: dict[str, list[dict[str, Any]]] = {}
    for r in data.get("glue_job_runs") or []:
        runs_by.setdefault(str(r["job"]), []).append(r)
    for job in sorted(runs_by):
        runs = sorted(runs_by[job], key=lambda r: str(r.get("started")), reverse=True)
        bad = [r for r in runs if r.get("state") in ("FAILED", "ERROR", "TIMEOUT") and _within(r.get("started"), now, 24)]
        if bad:
            sig.append(f"glue job {job}: {len(bad)} failed run(s) in 24h: {str(bad[0].get('error') or bad[0]['state'])[:100]}")
        done = [r for r in runs if r.get("state") == "SUCCEEDED" and isinstance(r.get("duration_s"), (int, float))]
        if runs and runs[0] in done and len(done) >= 5:
            last, prev = done[0]["duration_s"], [r["duration_s"] for r in done[1:5]]
            if last > GLUE_DURATION_X * _median(prev):
                sig.append(f"glue job {job}: last run {human_duration(last)}, > 2x the median of the previous 4")
    for c in sorted(data.get("glue_crawlers") or [], key=lambda r: str(r.get("name"))):
        if c.get("last_status") == "FAILED":
            sig.append(f"glue crawler {c['name']} last crawl failed: {str(c.get('error') or '')[:100]}")
    for t in sorted(data.get("glue_tables") or [], key=lambda r: (r["database"], str(r["name"]))):
        if t.get("partition_keys") and "partitions" in t and not t.get("partitions_truncated"):
            if t["partitions"] == 0 or not _within(t.get("last_partition_added"), now, GLUE_PARTITION_DAYS * 24):
                sig.append(f"glue table {t['database']}.{t['name']}: no partition added in {GLUE_PARTITION_DAYS} d")
    max_age = float(meta.get("max_age_h") or 26)
    for p in sorted(data.get("s3_prefixes") or [], key=lambda r: str(r.get("prefix"))):
        if p.get("source") == "error" or not p.get("newest_complete", True):
            continue
        if not p.get("object_count"):
            sig.append(f"s3 {p['prefix']}: no objects found")
        elif not _within(p.get("newest_at"), now, max_age):
            sig.append(f"s3 {p['prefix']}: newest object is older than {max_age:g} h ({_ts(p.get('newest_at'))})")
    max_gb = float(meta.get("max_scan_gb") or 100)
    for w in sorted(data.get("athena_workgroups") or [], key=lambda r: r["workgroup"]):
        if int(w.get("failed") or 0) > 0:
            reason = next((f["reason"] for f in data.get("athena_failures") or [] if f["workgroup"] == w["workgroup"]), "")
            sig.append(f"athena workgroup {w['workgroup']}: {w['failed']} failed query(ies) in 24h"
                       + (f" ({reason[:80]})" if reason else ""))
    for q in sorted(data.get("athena_top_queries") or [], key=lambda r: (r["workgroup"], str(r["query_id"]))):
        if isinstance(q.get("scanned_bytes"), (int, float)) and q["scanned_bytes"] > max_gb * 1024 ** 3:
            sig.append(f"athena query {q['query_id']} scanned {human_bytes(q['scanned_bytes'])} (> {max_gb:g} GB)")
    for f in sorted(data.get("firehose_streams") or [], key=lambda r: r["stream"]):
        if f.get("status") != "ACTIVE":
            sig.append(f"firehose stream {f['stream']} is {f.get('status')}")
        interval, fresh = f.get("buffer_interval_s"), f.get("freshness_p95_s")
        if isinstance(fresh, (int, float)) and isinstance(interval, (int, float)) and fresh > FIREHOSE_FRESH_X * interval:
            sig.append(f"firehose stream {f['stream']}: data freshness p95 {fresh:.0f} s (> 2x the {interval:.0f} s buffer)")
        ok = f.get("delivery_success")
        if isinstance(ok, (int, float)) and ok < 1.0:
            sig.append(f"firehose stream {f['stream']}: delivery success {ok:.2f} (< 1.0)")
    for a in sorted(data.get("cloudwatch_alarms") or [], key=lambda r: str(r.get("name"))):
        sig.append(f"cloudwatch alarm {a['name']} in ALARM since {_ts(a.get('since'))}")
    return sig


