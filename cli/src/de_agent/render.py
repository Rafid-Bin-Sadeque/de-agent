RS_USER_SHARE_PCT = 70.0
RS_QUEUE_P95_S = 30.0
RS_SPILL_MB = 1024.0
RS_COMMIT_P95_S = 10.0
RS_UNSORTED_PCT = 20.0
RS_STATS_OFF = 10.0
RS_SKEW_ROWS = 4.0
RS_SKEW_MIN_MB = 1024.0


def _names(rows: list[dict[str, Any]], limit: int = 3) -> str:
    names = [f"{r['schema']}.{r['name']}" for r in rows]
    more = f" (+{len(names) - limit} more)" if len(names) > limit else ""
    return ", ".join(names[:limit]) + more


def redshift_signals(data: dict[str, Any]) -> list[str]:
    sig: list[str] = []
    for u in sorted(data.get("workload_users") or [], key=lambda r: str(r.get("user"))):
        pct = u.get("share_pct")
        if isinstance(pct, (int, float)) and pct > RS_USER_SHARE_PCT:
            sig.append(f"workload is dominated by {u['user']} ({pct:.0f}% of exec time in 24h); "
                       f"check what {u['user']} is before attributing")
    w = data.get("workload_24h") or {}
    q95 = w.get("queue_p95_s")
    if isinstance(q95, (int, float)) and q95 > RS_QUEUE_P95_S:
        sig.append(f"queue wait p95 {q95:.0f} s (> {RS_QUEUE_P95_S:.0f} s)")
    p = data.get("pressure_24h") or {}
    spill = p.get("spilled_mb")
    if isinstance(spill, (int, float)) and spill > RS_SPILL_MB:
        sig.append(f"{int(p.get('spilled_queries') or 0)} queries spilled {human_bytes(spill * 1024 * 1024)} to disk in 24h")
    cq = p.get("commit_queue_p95_s")
    if isinstance(cq, (int, float)) and cq > RS_COMMIT_P95_S:
        sig.append(f"commit queue wait p95 {cq:.1f} s (> {RS_COMMIT_P95_S:.0f} s)")
    tabs = sorted(data.get("tables") or [], key=lambda r: (-(r.get("size_mb") or 0), str(r.get("schema")), str(r.get("name"))))
    unsorted = [t for t in tabs if isinstance(t.get("unsorted_pct"), (int, float)) and t["unsorted_pct"] > RS_UNSORTED_PCT]
    if unsorted:
        sig.append(f"{len(unsorted)} table(s) over {RS_UNSORTED_PCT:.0f}% unsorted: {_names(unsorted)}")
    stale = [t for t in tabs if isinstance(t.get("stats_off"), (int, float)) and t["stats_off"] > RS_STATS_OFF]
    if stale:
        sig.append(f"{len(stale)} table(s) with stats_off > {RS_STATS_OFF:.0f}: {_names(stale)}")
    skewed = [t for t in tabs if isinstance(t.get("skew_rows"), (int, float)) and t["skew_rows"] > RS_SKEW_ROWS
              and (t.get("size_mb") or 0) > RS_SKEW_MIN_MB]
    if skewed:
        sig.append(f"{len(skewed)} table(s) over 1 GB with skew_rows > {RS_SKEW_ROWS:.0f}: {_names(skewed)}")
    blocked = [r for r in data.get("locks") or [] if r.get("kind") == "blocked"]
    if blocked:
        sig.append(f"{len(blocked)} blocked session(s)")
    errs = data.get("load_errors_24h") or []
    if errs:
        n = sum(int(e.get("count") or 0) for e in errs)
        tables = ", ".join(sorted({str(e.get("table")) for e in errs})[:3])
        sig.append(f"{n} load error(s) in 24h ({tables})")
    return sig


def _redshift_body(data: dict[str, Any]) -> list[str]:
    out: list[str] = []
    secs = (data.get("meta") or {}).get("sections") or {}

    def aged(*names: str) -> str:
        """" (from snapshot N h ago)" when the section was reused from an earlier snapshot."""
        for n in names:
            h = (secs.get(n) or {}).get("cached_age_h")
            if (secs.get(n) or {}).get("cached_from") and isinstance(h, (int, float)):
                return f" (from snapshot {h:g} h ago)"
        return ""

    c = data.get("cluster")
    if c:
        m = re.search(r"Redshift \d+(\.\d+)*", str(c.get("version", "")))
        rows = [["version", m.group(0) if m else str(c.get("version", "-")).split(" on ")[0]],
                ["kind", str(c.get("kind", "-"))], ["nodes", _num(c.get("nodes"))], ["slices", _num(c.get("slices"))]]
        for k, v in sorted((c.get("aws") or {}).items()):
            rows.append([f"aws {k}", _num(v)])
        out += ["## Cluster", ""] + _table(["key", "value"], rows) + [""]
    w = data.get("workload_24h")
