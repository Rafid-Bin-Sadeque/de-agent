"""`dea config schema`: the de-agent.yaml reference, generated from the pydantic models.

`json_schema()` is the machine-readable form (docs/de-agent.schema.json, usable for editor validation);
`markdown()` is docs/configuration.md. A test fails when either committed file drifts from the models.
"""
from __future__ import annotations

import json
from typing import Any

from de_agent.config import Config

SECTIONS = [  # (heading, $defs key or None for the root, yaml path shown in the heading)
    ("Top level", None, ""),
    ("`hub`", "HubConfig", "hub"),
    ("`guard`", "GuardConfig", "guard"),
    ("`sources[]`", "SourceConfig", "sources[]"),
    ("`sources[].conn`", "ConnConfig", "sources[].conn"),
    ("`scans[]`", "ScanConfig", "scans[]"),
]

HEAD = """# Configuration reference: `de-agent.yaml`

<!-- Generated by `dea config schema --markdown` from the pydantic models in cli/src/de_agent/config.py.
     Do not edit by hand: a test fails when this file drifts. JSON Schema: de-agent.schema.json -->

`de-agent.yaml` sits at the root of the hub. `dea init` writes a starter. Unknown keys are errors. The file holds
secret references only: a literal value in any key named `password`, `token` or ending in `_secret` / `_key` is a load error.

Secret references: `pgpass` (libpq decides, from `~/.pgpass`), `none`, `env:NAME` (read at run time from the process environment, else from a `.env` file in the hub directory if there is one;
`dea` reads it itself, it is never printed and the agent cannot read `.env`), `file:/absolute/path`
(must be mode 0600 or stricter). Over `exec: ssh:<host>` only `pgpass` is allowed, because the secret is resolved on the remote host.

```yaml
version: 1
hub: {name: "Acme data platform", snapshot_max_age_hours: 24}
sources:
  - name: warehouse
    type: postgres
    conn: {host: db.example.internal, dbname: shop, user: readonly_agent, password: pgpass}
scans:
  - {name: pipelines, type: airflow, path: ../airflow, dag_folders: [dags]}
guard: {mode: strict}
```

Per-collector `options` and the `aws`, `data_api` and `services` blocks are documented with each collector
(for Redshift and AWS: [collectors.md](collectors.md)).
"""


def json_schema() -> dict[str, Any]:
    schema = Config.model_json_schema()
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["title"] = "de-agent.yaml"
    return schema


def json_text() -> str:
    return json.dumps(json_schema(), indent=2, sort_keys=False) + "\n"


def _resolve(schema: dict[str, Any], node: dict[str, Any]) -> dict[str, Any]:
    if "$ref" in node:
        return schema["$defs"][node["$ref"].rsplit("/", 1)[-1]]
    return node


def _type(schema: dict[str, Any], node: dict[str, Any]) -> str:
    if "$ref" in node:
        return f"object ({node['$ref'].rsplit('/', 1)[-1]})"
    if "anyOf" in node:
        parts = [_type(schema, n) for n in node["anyOf"] if n.get("type") != "null"]
        return " or ".join(parts) + (" or null" if any(n.get("type") == "null" for n in node["anyOf"]) else "")
    t = node.get("type", "any")
    if t == "array":
        return f"list of {_type(schema, node.get('items', {}))}"
    if t == "integer" and ("minimum" in node or "exclusiveMinimum" in node):
        lo = node.get("minimum", node.get("exclusiveMinimum"))
        return f"integer (>= {lo})" if "minimum" in node else f"integer (> {lo})"
    if t == "number" and "exclusiveMinimum" in node:
        return f"number (> {node['exclusiveMinimum']})"
    return str(t)


def _default(node: dict[str, Any], required: bool) -> str:
    if required:
        return "required"
    if "default" not in node:
        return ""
    d = node["default"]
    if d is None:
        return "unset"
    if d in ([], {}):
        return "empty"
    return f"`{json.dumps(d)}`"


def _table(schema: dict[str, Any], model: dict[str, Any]) -> list[str]:
    req = set(model.get("required", []))
    rows = ["| key | type | default | description |", "|---|---|---|---|"]
    for key, node in model.get("properties", {}).items():
        desc = (node.get("description") or "").replace("|", "\\|").replace("\n", " ")
        rows.append(f"| `{key}` | {_type(schema, node)} | {_default(node, key in req)} | {desc} |")
    return rows


def markdown() -> str:
    schema = json_schema()
    out = [HEAD.rstrip(), ""]
    for heading, key, _path in SECTIONS:
        model = schema if key is None else schema["$defs"][key]
        out += [f"## {heading}", ""] + _table(schema, model) + [""]
    return "\n".join(out)
