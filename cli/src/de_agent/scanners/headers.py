"""Generated profile headers (M1c section 4): rewrite ONLY the text between the dea:generated markers."""
from __future__ import annotations

import re
from collections import Counter
from pathlib import Path
from typing import Any

START = "<!-- dea:generated:start -->"
END = "<!-- dea:generated:end -->"
FM_RE = re.compile(r"\A---[ \t]*\r?\n.*?\r?\n---[ \t]*(?:\r?\n|\Z)", re.S)


def marker_state(text: str) -> str:
    """ok | none | broken (one marker without its pair, or end before start, or duplicates)."""
    n_s, n_e = text.count(START), text.count(END)
    if n_s == 0 and n_e == 0:
        return "none"
    if n_s == 1 and n_e == 1 and text.index(START) < text.index(END):
        return "ok"
    return "broken"


def block_lines(text: str) -> int:
    if marker_state(text) != "ok":
        return 0
    return text[text.index(START):text.index(END) + len(END)].count("\n") + 1


def apply_block(text: str, block: str) -> str | None:
    """Return the new page text, or None when the markers are malformed (page left untouched)."""
    state = marker_state(text)
    if state == "broken":
        return None
    if state == "ok":
        a, b = text.index(START), text.index(END) + len(END)
        return text[:a] + block + text[b:]
    m = FM_RE.match(text)
    pos = m.end() if m else 0
    prefix = text[:pos]
    if prefix and not prefix.endswith("\n"):
        prefix += "\n"
    return prefix + block + "\n\n" + text[pos:]


def _top(counter: Counter, n: int = 10) -> str:
    items = sorted(counter.items(), key=lambda kv: (-kv[1], kv[0]))[:n]
    return ", ".join(f"{k} ({v})" for k, v in items) or "none"


def build_block(project: str, results: list[dict[str, Any]], edges: dict[str, Any], repos: dict[str, dict[str, Any]],
                profiles: set[str], catalog_links: list[tuple[str, str]]) -> str:
    """The generated block for one project. `repos` maps scan name -> {path, commit}."""
    L = [START, "", "<!-- generated by `dea scan`; edit nothing between these markers -->", ""]
    writes: Counter = Counter()
    reads: Counter = Counter()
    for t, v in edges["tables"].items():
        for w in v["writers"]:
            if w["project"] == project:
                writes[t] += 1
        for r in v["readers"]:
            if r["project"] == project:
                reads[t] += 1
    for r in results:
        scan = r["scan"]
        info = repos.get(scan, {})
        L.append(f"- repo: `{info.get('path', '?')}` (scan `{scan}`, {r['type']}, revision `{r['revision']}`)")
        c = info.get("commit")
        if c:
            L.append(f"- last commit: `{c['hash']}` {c['date']} — {c['subject']}")
        st = r["stats"]
        if r["type"] == "airflow":
            L.append(f"- {st['dags']} DAGs ({st['dynamic_dags']} dynamic), {len(r['symbols'])} util symbols; unresolved: "
                     f"{st['unresolved_calls']} calls, {st['unresolved_sql']} dynamic SQL, {st['unresolved_datasets']} datasets")
        elif r["type"] == "dbt":
            L.append(f"- {st['models']} models, {st['sources']} sources, {st['exposures']} exposures")
        else:
            L.append(f"- {st['objects']} SQL objects in {st['files']} files ({st['heuristic']} heuristic)")
    L.append(f"- top tables written: {_top(writes)}")
    L.append(f"- top tables read: {_top(reads)}")
    cross: dict[tuple[str, str, str], None] = {}
    for c in edges["cross_project"]:
        if c["writer_project"] == project:
            cross[("→", c["reader_project"], c["table"])] = None
        elif c["reader_project"] == project:
            cross[("←", c["writer_project"], c["table"])] = None
    if cross:
        L.append("- cross-project edges:")
        for arrow, other, table in sorted(cross, key=lambda k: (k[1], k[2], k[0])):
            link = f"[[{other}]]" if other in profiles else other
            verb = "writes for" if arrow == "→" else "reads from"
            L.append(f"  - {arrow} {link} via table `{table}` ({verb})")
    else:
        L.append("- cross-project edges: none")
    for label, href in catalog_links:
        L.append(f"- catalog: [{label}]({href})")
    L += ["", END]
    return "\n".join(L)


def rewrite_profile(path: Path, block: str) -> str:
    """Write the block into the page. Returns 'updated' | 'unchanged' | 'broken-markers'. Bytes outside are preserved."""
    raw = path.read_bytes()
    text = raw.decode("utf-8")
    new = apply_block(text, block)
    if new is None:
        return "broken-markers"
    if new == text:
        return "unchanged"
    path.write_bytes(new.encode("utf-8"))
    return "updated"
