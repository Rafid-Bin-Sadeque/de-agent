import json
import os
from pathlib import Path

import pytest
from de_agent import render as R

HERE = Path(__file__).parent
CASES = ["pg_full", "pg_healthy", "pg_partial"]


def load(name):
    return json.loads((HERE / "fixtures" / f"{name}.json").read_text())


@pytest.mark.parametrize("name", CASES)
def test_golden(name):
    got = R.render(load(name))
    golden = HERE / "golden" / f"{name}.md"
    if os.environ.get("DEA_UPDATE_GOLDEN"):
        golden.write_text(got)
    assert got == golden.read_text()


@pytest.mark.parametrize("name", CASES)
def test_deterministic(name):
    r = load(name)
    a, b = R.render(r), R.render(json.loads(json.dumps(r)))
    assert a.encode() == b.encode()


def test_shuffled_rows_render_identically():
    r = load("pg_full")
    s = json.loads(json.dumps(r))
    for k in ("tables", "databases", "schemas", "long_queries", "replication_slots", "settings"):
        s["data"][k] = list(reversed(s["data"][k]))
    assert R.render(r) == R.render(s)


def test_signals_exact():
    sig = R.signals_for(load("pg_full"))
    assert sig == [
        "xid age 60% of wraparound",
        "connections 85 of 100 (85%)",
        "cache hit ratio 93.4% (< 95%)",
        "table analytics.orders 34% dead tuples",
        "2 queries running > 5 min",
        "1 blocked session(s)",
        "slot cdc_slot inactive, lag 3.1 GB",
        "1 unused index(es), 20.0 MB",
    ]
    assert R.signals_for(load("pg_healthy")) == []


def test_thresholds_are_boundaries():
    base = load("pg_healthy")
    t = {"schema": "s", "name": "t", "n_dead_tup": 99_999, "dead_pct": 50.0}
    base["data"]["tables"] = [t]
    assert R.signals_for(base) == []                       # < 100k dead: no signal
    t["n_dead_tup"], t["dead_pct"] = 100_000, 19.9
    assert R.signals_for(base) == []                       # < 20%: no signal
    t["dead_pct"] = 20.0
    assert R.signals_for(base) == ["table s.t 20% dead tuples"]
    base["data"]["tables"] = []
    base["data"]["server"]["xid_wraparound_pct"] = 49.9
    assert R.signals_for(base) == []
    base["data"]["server"]["xid_wraparound_pct"] = 50.0
    assert R.signals_for(base) == ["xid age 50% of wraparound"]
    base["data"]["server"]["xid_wraparound_pct"] = 0
    base["data"]["server"]["connections_total"] = 80
    assert R.signals_for(base) == ["connections 80 of 100 (80%)"]
    base["data"]["server"]["connections_total"] = 7
    base["data"]["replication_slots"] = [{"slot_name": "a", "active": True, "lag_bytes": 1024**3}]
    assert R.signals_for(base) == []                       # lag must exceed 1 GB
    base["data"]["replication_slots"][0]["lag_bytes"] = 1024**3 + 1
    assert R.signals_for(base) == ["slot a active, lag 1.0 GB"]


def test_human_bytes():
    assert R.human_bytes(0) == "0 B"
    assert R.human_bytes(1023) == "1023 B"
    assert R.human_bytes(1024) == "1.0 KB"
    assert R.human_bytes(1536) == "1.5 KB"
    assert R.human_bytes(5 * 1024**2) == "5.0 MB"
    assert R.human_bytes(3328599654) == "3.1 GB"
    assert R.human_bytes(None) == "-"


def test_structure_header_and_frontmatter():
    out = R.render(load("pg_full"))
    assert out.startswith("---\nsource: warehouse\ntype: postgres\ngenerated: 2026-10-27T09:00:00Z\nschema_version: 1\n---\n")
    assert "GENERATED by dea snapshot — do not edit" in out
    assert out.index("## Signals") < out.index("## Server") < out.index("## Tables")
    assert "## Errors" not in out
    assert "## Errors" in R.render(load("pg_partial"))


def test_unknown_type_renders_header_only():
    out = R.render({"source": "x", "type": "other", "schema_version": 1, "collected_at": "2026-01-01T00:00:00Z",
                    "data": {}, "errors": []})
    assert "## Signals" in out and "- none" in out
